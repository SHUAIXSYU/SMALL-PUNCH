"""Finish the recovered CAE verification task using the real AgentHub session."""

from __future__ import annotations

import hashlib
import json
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
HUB_DIR = ROOT / "agenthub_sp_invopt"
sys.path.insert(0, str(HUB_DIR))
from hub import Hub

TASK_ID = "a4b4805f-4989-4168-a54a-3bbf435b52a6"
SESSION_ID = "aa78d383-febb-4b7e-99d5-2a9665e9ab6c"
AGENT_ID = "CAE:cae-codex-20261021-632ffd48"
EXPECTED_INP_SHA = "fa2de5d73a28536c1c07cd22072d2a24c1ae988c569127d728931c583457f05a"
EXPECTED_REPORT_SHA = "9f5904278e44696dad337646fa1ee6b486b0e7a43965dbde46086e6c9c7293e7"
EXPECTED_SOURCE_SHA = "b2aac48af9529db28873c19f047f479c63ed247884f9bdc5fd7bccd5763305cc"
CAE_DIR = ROOT / "run" / "run_010" / "artifacts" / "cae"
INP_REL = "run/run_008/artifacts/candidate_inp/SPIO_R008_Q200_N010_Candidate/SPIO_R008_Q200_N010_Candidate.inp"
DB = HUB_DIR / "runtime" / "sp_invopt.sqlite3"
LEASE_FILE = HUB_DIR / "runtime" / "cae_lease_a4b4805f_632ffd48_generation2.json"
RECEIPT_FILE = CAE_DIR / "completion_receipt.json"


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def require(condition: bool, label: str) -> None:
    if not condition:
        raise RuntimeError(label)


def now_iso() -> str:
    return datetime.now(timezone(timedelta(hours=8))).isoformat()


def main() -> None:
    require(not LEASE_FILE.exists(), "Generation-2 lease file already exists")
    require(not RECEIPT_FILE.exists(), "Completion receipt already exists")
    hub = Hub(DB, lease_seconds=300)
    identity = hub.session_identity(SESSION_ID)
    require(identity["agent_id"] == AGENT_ID and identity["role"] == "CAE", "CAE session mismatch")
    task = hub.task(TASK_ID)
    require(task is not None and task["execution_state"] == "PENDING", "Recovered task is not pending")
    require(task["generation"] == 1 and task["kind"] == "verify_inp", "Task generation/kind mismatch")
    hub.require_approval(TASK_ID, "verify_inp")
    payload = json.loads(task["payload"])
    require(payload["run_id"] == "run_010" and payload["inp"] == INP_REL, "Task input mismatch")
    require(payload["expected_sha256"] == EXPECTED_INP_SHA, "Task hash mismatch")
    require(payload["parameters"] == {"E_GPa": 210, "nu": 0.3, "sigma_y_MPa": 200,
                                        "n": 0.1, "max_plastic_strain": 0.9}, "Task parameters mismatch")
    report_path = CAE_DIR / "verification.json"
    report = json.loads(report_path.read_text(encoding="utf-8"))
    require(report["task_id"] == TASK_ID and report["status"] == "PASS_STATIC_INP_VERIFICATION", "Report status mismatch")
    require(all(report["checks"].values()), "At least one static check failed")
    require(sha(report_path) == EXPECTED_REPORT_SHA, "Verification report changed")
    require(sha(ROOT / INP_REL) == EXPECTED_INP_SHA, "Candidate INP changed")
    require(sha(ROOT / report["source_relative_path"]) == EXPECTED_SOURCE_SHA, "Historical source INP changed")
    require(sha(ROOT / report["generator_relative_path"]) == report["generator_sha256"], "Generator changed")
    require((ROOT / "run/run_010/checkpoints/cae_stopped_before_recovery.json").is_file(), "Recovery stop evidence missing")

    lease = hub.claim(TASK_ID, identity, "run010-cae-codex-632ffd48-generation2")
    require(lease["generation"] == 2, "Expected recovered generation 2")
    LEASE_FILE.write_text(json.dumps(lease, indent=2) + "\n", encoding="utf-8")

    base = {
        "task_id": TASK_ID,
        "source_relative_path": report["source_relative_path"],
        "source_sha256": EXPECTED_SOURCE_SHA,
        "candidate_relative_path": INP_REL,
        "candidate_sha256": EXPECTED_INP_SHA,
        "method": "Read-only static verification; no Abaqus parser, datacheck, Solver, or queue action",
        "recovery": "Generation 1 lease expired; MAIN confirmed worker stopped and recovered task",
    }
    specs = [
        (ROOT / INP_REL, "candidate-true-total-hollomon-v1", "Existing run_008 candidate; re-registered as verified input, not generated by this session"),
        (report_path, "cae-static-verification-v1", "Successful independent static verification report"),
        (CAE_DIR / "verify_candidate_inp.py", "cae-static-verification-v1", "Reproducible verification script"),
        (CAE_DIR / "verification_attempt01.json", "cae-static-verification-attempt01-v1", "Preserved false-negative check before boundary correction"),
    ]
    artifacts = []
    for path, version, meaning in specs:
        provenance = dict(base, meaning=meaning)
        row = hub.artifact(TASK_ID, AGENT_ID, path, provenance, version=version)
        artifacts.append({"artifact_id": row["artifact_id"],
                          "path": str(path.relative_to(ROOT)).replace("\\", "/"),
                          "sha256": row["sha256"], "version": version})

    result = {
        "task_id": TASK_ID,
        "agent_id": AGENT_ID,
        "session_id": SESSION_ID,
        "generation": lease["generation"],
        "execution_status": "COMPLETED",
        "evidence_status": "RECORDED",
        "science_status": "NOT_EVALUATED",
        "static_verification": "PASS_STATIC_INP_VERIFICATION",
        "checks_passed": len(report["checks"]),
        "candidate_sha256": EXPECTED_INP_SHA,
        "artifacts": artifacts,
        "limitations": [
            "Historical source INP equivalence with the currently edited CAE database is UNKNOWN",
            "Candidate material interpretation is not experimentally validated",
            "AbqJobPilot Settings/preflight/dry-run audited separately by MAIN as BLOCKED; CAE did not run them",
            "No fresh Abaqus parser, datacheck, Solver, or queue operation",
        ],
    }
    hub.finish(lease, result, evidence_state="RECORDED", science_state="NOT_EVALUATED")
    message = hub.message(TASK_ID, AGENT_ID, "MAIN", result,
                          "run010-cae-generation2-completed-632ffd48")
    final_task = hub.task(TASK_ID)
    require(final_task["execution_state"] == "COMPLETED", "Completion not persisted")
    receipt = {
        "observed_at": now_iso(),
        "task_id": TASK_ID,
        "agent_id": AGENT_ID,
        "session_id": SESSION_ID,
        "generation": lease["generation"],
        "execution_state": final_task["execution_state"],
        "evidence_state": final_task["evidence_state"],
        "science_state": final_task["science_state"],
        "artifacts": artifacts,
        "main_message_id": message["message_id"],
        "audit_hash_chain_valid": hub.verify_chain(),
    }
    RECEIPT_FILE.write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (CAE_DIR / "result.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(receipt, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
